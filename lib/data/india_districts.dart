/// Districts and union-territory subdivisions offered after a state is picked.
///
/// The leaderboard files a user under `district_<state>_<district-slug>`, so a
/// picker beats free text: "Pune", "pune" and "Poona" typed by three people
/// made three half-empty boards. The picker keeps each area on one board.
///
/// The lists follow the current official districts (including the 2022-2024
/// renames and splits). They are not a boundary authority: a district that is
/// missing, or a spelling the list does not carry, is handled by the "Other"
/// entry in the picker, which types a name exactly as the old field did.
library;

/// Whether [label] matches a search [query], ignoring case and outer spaces.
///
/// An empty query matches everything, so a picker shows its whole list until
/// the user types. Shared by the country, state and district searches so all
/// three behave the same way.
bool matchesSearch(String label, String query) {
  final needle = query.trim().toLowerCase();
  return needle.isEmpty || label.toLowerCase().contains(needle);
}

